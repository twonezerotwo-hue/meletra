LECTURES = {"heart_failure": HEART_FAILURE, "antibiotics": ANTIBIOTICS, "thyroid": THYROID}


def segments(name: str, seconds: float = 18.0) -> list[dict]:
    """The lecture as transcript segments with real, increasing times."""
    return [{"start": i * seconds, "end": (i + 1) * seconds - 0.5, "text": text} for i, text in enumerate(LECTURES[name])]
